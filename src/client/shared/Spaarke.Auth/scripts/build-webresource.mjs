/**
 * build-webresource.mjs — bundle @spaarke/auth (with MSAL) into the classic web resource
 * `sprk_/scripts/bff_auth.js`, the `Spaarke.BffAuth` helper every Dataverse form script and
 * ribbon command calls (#1655).
 *
 *   npm run build:webresource           write both committed copies
 *   npm run build:webresource -- --check  exit 1 when a committed copy differs from a fresh build
 *
 * Output: one IIFE, minified, no external loads. MSAL is bundled from this package's own
 * @azure/msal-browser (the library's peer range ^3, the same major as the PCFs on the same
 * forms, so both read one localStorage cache format). Nothing is fetched from a CDN at runtime.
 *
 * The bundle is written to both places the web resource lives, kept identical:
 *   - src/solutions/webresources/sprk_bff_auth.js                         (canonical source copy)
 *   - src/dataverse/solutions/SpaarkeMaster/WebResources/sprk_/scripts/bff_auth.js (solution copy)
 * Deploy either with scripts/Deploy-WebResourceInline.ps1 (-WebResourceType 3).
 *
 * Same tool and shape as src/solutions/SpaarkeAi/scripts/build-ribbon.mjs (esbuild, IIFE).
 */

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '..', '..', '..', '..');

const ENTRY = join(pkgRoot, 'src', 'webresource', 'bffAuth.entry.ts');
const TARGETS = [
  join(repoRoot, 'src', 'solutions', 'webresources', 'sprk_bff_auth.js'),
  join(repoRoot, 'src', 'dataverse', 'solutions', 'SpaarkeMaster', 'WebResources', 'sprk_', 'scripts', 'bff_auth.js'),
];

/** Inputs that must never reach a form-script bundle (React/Fluent would mean a wrong import). */
const FORBIDDEN_INPUT = [
  /(^|\/)node_modules\/react\//,
  /(^|\/)node_modules\/react-dom\//,
  /(^|\/)node_modules\/@fluentui\//,
];

const msalVersion = JSON.parse(
  readFileSync(join(pkgRoot, 'node_modules', '@azure', 'msal-browser', 'package.json'), 'utf8')
).version;
const libVersion = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8')).version;

const banner = [
  '/*!',
  ' * Spaarke BFF Auth — web resource sprk_/scripts/bff_auth.js (Spaarke.BffAuth)',
  ` * GENERATED by src/client/shared/Spaarke.Auth/scripts/build-webresource.mjs — do not edit.`,
  ' * Source: src/client/shared/Spaarke.Auth/src/webresource/bffAuth.ts',
  ` * Bundles @spaarke/auth ${libVersion} and @azure/msal-browser ${msalVersion} (MIT, Microsoft).`,
  ' * Register on a form BEFORE every library that calls Spaarke.BffAuth (#1655, ADR-028, ADR-006).',
  ' */',
].join('\n');

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'eof',
  banner: { js: banner },
  charset: 'utf8',
  write: false,
  metafile: true,
  logLevel: 'warning',
});

const offenders = Object.keys(result.metafile.inputs)
  .map(i => i.split('\\').join('/'))
  .filter(i => FORBIDDEN_INPUT.some(re => re.test(i)));
if (offenders.length > 0) {
  console.error(`FAIL forbidden inputs in the bff_auth.js bundle:\n  ${offenders.join('\n  ')}`);
  process.exit(1);
}

const output = result.outputFiles[0].text.replace(/\r\n/g, '\n');
const check = process.argv.includes('--check');
let drift = 0;

for (const target of TARGETS) {
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      /* missing counts as drift */
    }
    if (current !== output) {
      console.error(`DRIFT ${target} differs from a fresh build — run npm run build:webresource`);
      drift++;
    } else {
      console.log(`ok    ${target}`);
    }
  } else {
    writeFileSync(target, output, 'utf8');
    console.log(`wrote ${target} (${Buffer.byteLength(output, 'utf8')} bytes)`);
  }
}

if (drift > 0) process.exit(1);
